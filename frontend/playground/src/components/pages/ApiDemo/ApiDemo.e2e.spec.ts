import { test, expect } from '@playwright/test';
test.beforeEach(async ({ page }) => {
  await page.goto('/questions/api');
});
test('manual blocks incomplete input and emits answer only after grading', async ({ page }) => {
  const q = page.getByRole('region', { name: /Ручна перевірка:/ });
  const events = page.getByRole('status', { name: 'Події контролера' });
  await expect(q.getByRole('button', { name: 'Перевірити', exact: true })).toBeDisabled();
  await expect(events).not.toContainText('manual-check');
  await q.getByRole('button', { name: '3', exact: true }).click();
  await expect(q.getByRole('status', { name: 'Результат перевірки' })).toBeEmpty();
  await q.getByRole('button', { name: 'Перевірити', exact: true }).click();
  await expect(events).toContainText('manual-answer:1:incorrect');
  await expect(events).toContainText('manual-incorrect:1:incorrect');
});
test('automatic grading and hidden feedback still emit one ordered lifecycle', async ({ page }) => {
  await page.getByRole('checkbox', { name: 'Приховати результат автоматичної перевірки' }).check();
  const q = page.getByRole('region', { name: /Автоматична перевірка:/ });
  await q.getByRole('button', { name: '2', exact: true }).click();
  await expect(q.getByRole('status', { name: 'Результат перевірки' })).toBeEmpty();
  await expect(q.getByRole('button', { name: '3', exact: true })).toBeDisabled();
  const events = page.getByRole('status', { name: 'Події контролера' });
  await expect(events).toHaveText('change:1:editing\ncheck:1:correct\nanswer:1:correct\ncorrect:1:correct');
  await q.getByRole('button', { name: 'Спробувати ще раз' }).click();
  await expect(q.getByRole('button', { name: '2', exact: true })).toHaveAttribute('aria-pressed', 'false');
  await q.getByRole('button', { name: '3', exact: true }).click();
  await expect(q.getByRole('button', { name: 'Спробувати ще раз' })).toBeVisible();
  await page.getByRole('checkbox', { name: 'Приховати результат автоматичної перевірки' }).uncheck();
  await expect(q.getByRole('status', { name: 'Результат перевірки' })).toBeEmpty();
  await expect(q.getByText('Пояснення:', { exact: false })).toHaveCount(0);
  await expect(events).toContainText('answer:2:incorrect');
  await q.getByRole('button', { name: 'Скинути', exact: true }).click();
  await expect(events).toContainText('reset:1:editing');
});
test('custom root/question/answers/actions slots share state and cannot bypass locks', async ({ page }) => {
  const q = page.getByRole('region', { name: /Власні слоти:/ });
  await expect(q).toHaveAttribute('data-custom-root', 'true');
  const input = q.getByRole('textbox', { name: 'Власне числове поле' });
  const state = q.getByRole('status', { name: 'Стан спроби' });
  await expect(state).toContainText('hasInteracted=false; isModified=false');
  await input.fill('4');
  await input.fill('');
  await expect(state).toContainText('hasInteracted=true; isModified=false');
  await input.fill('42');
  await q.getByRole('button', { name: 'Власна перевірка', exact: true }).click();
  await expect(q.getByRole('status', { name: 'Результат перевірки' })).toBeEmpty();
  await expect(input).toBeDisabled();
  await q.getByRole('button', { name: 'Власна повторна спроба' }).click();
  await expect(input).toHaveValue('42');
  await q.getByRole('button', { name: 'Власне скидання' }).click();
  await page.getByRole('checkbox', { name: 'Disabled для власних слотів' }).check();
  // These custom buttons are deliberately enabled; the controller must enforce the guard.
  await q.getByRole('button', { name: 'Встановити 42 через API' }).click();
  await expect(input).toHaveValue('');
  await page.getByRole('checkbox', { name: 'Disabled для власних слотів' }).uncheck();
  await page.getByRole('checkbox', { name: 'Read-only для власних слотів' }).check();
  await q.getByRole('button', { name: 'Встановити 42 через API' }).click();
  await expect(input).toHaveValue('');
  await page.getByRole('checkbox', { name: 'Read-only для власних слотів' }).uncheck();
  await q.getByRole('button', { name: 'Встановити 42 через API' }).click();
  await expect(input).toHaveValue('42');
});
