import { test, expect } from '@playwright/test';
test('student sees demo progress and can open the next section with a Flag form', async ({ page }, testInfo) => {
  await page.goto('/student');
  await expect(page.getByRole('heading', { name: 'Кабінет учня', exact: true })).toBeVisible();
  await expect(page.getByRole('progressbar', { name: /Прогрес:/ })).toHaveAttribute('aria-valuenow', '50');
  await page.screenshot({ path: testInfo.outputPath('student.png'), fullPage: true });
  await page.getByRole('link', { name: 'Продовжити: Флешкартки' }).click();
  await expect(page).toHaveURL(/\/lessons\/light#flashcards$/);
  const section = page.getByRole('region', { name: 'Флешкартки', exact: true });
  await section.getByRole('button', { name: /^Flag:/ }).click();
  const dialog = page.getByRole('dialog', { name: 'Повідомити про помилку' });
  await dialog.getByRole('textbox', { name: 'Опишіть проблему' }).fill('У поясненні є помилка, перевірте, будь ласка.');
  await dialog.getByRole('button', { name: 'Надіслати повідомлення' }).click();
  await expect(dialog.getByRole('status')).toContainText('ще не налаштоване');
  await expect(dialog.getByRole('textbox', { name: 'Опишіть проблему' })).not.toHaveValue('');
});
test('teacher builds a named draft from catalog without pretending to persist it', async ({ page }) => {
  await page.goto('/teacher');
  const builder = page.getByRole('region', { name: 'Конструктор програми' });
  await builder.getByRole('button', { name: 'Підготувати програму' }).click();
  await expect(builder.getByRole('status')).toContainText('Назва повинна');
  await builder.getByRole('textbox', { name: 'Назва програми' }).fill('Моя фізика');
  await builder.getByRole('checkbox', { name: 'Як рухається світло' }).check();
  await builder.getByRole('button', { name: 'Підготувати програму' }).click();
  await expect(builder.getByRole('status')).toContainText('Збереження змін ще не підключене');
  await builder.getByRole('textbox', { name: 'Знайти урок' }).fill('неіснуючий');
  await expect(builder.getByText('За цим запитом уроків не знайдено.')).toBeVisible();
  await page.reload();
  await expect(builder.getByRole('textbox', { name: 'Назва програми' })).toHaveValue('');
});
test('admin edit and removal are safe stubs; catalog remains unchanged', async ({ page }) => {
  await page.goto('/admin/lessons');
  await page.getByRole('button', { name: 'Редагувати', exact: true }).click();
  const edit = page.getByRole('dialog', { name: 'Редагування уроку' });
  await edit.getByRole('textbox', { name: 'Назва уроку' }).fill('Змінений урок');
  await edit.getByRole('button', { name: 'Підготувати зміни' }).click();
  await expect(edit.getByRole('status')).toContainText('Збереження змін ще не підключене');
  await edit.getByRole('button', { name: 'Закрити', exact: true }).click();
  await expect(page.getByRole('table', { name: 'Наявні уроки' })).toContainText('Як рухається світло');
  await page.getByRole('button', { name: 'Видалити', exact: true }).click();
  const remove = page.getByRole('dialog', { name: 'Видалення уроку' });
  await remove.getByRole('button', { name: 'Підготувати видалення' }).click();
  await expect(remove.getByRole('status')).toContainText('Дані залишилися без змін');
  await remove.getByRole('button', { name: 'Скасувати' }).click();
  await expect(page.getByRole('table')).toContainText('Як рухається світло');
  await page.getByRole('textbox', { name: 'Пошук уроків' }).fill('відсутній');
  await expect(page.getByRole('table')).toContainText('Уроків не знайдено');
});
test('Flag submits material context once and shows only a confirmed issue link', async ({ page }) => {
  let calls = 0;
  await page.route('**/api/reports', async route => {
    calls++; const body = route.request().postDataJSON();
    expect(body.contentId).toBe('question:planet'); expect(body.message).toContain('Приклад проблеми'); expect(body.repository).toBeUndefined();
    await route.fulfill({ status: 201, contentType: 'application/json', body: JSON.stringify({ status: 'created', issueNumber: 42, issueUrl: 'https://github.com/example/content/issues/42' }) });
  });
  await page.goto('/questions');
  await page.getByRole('region', { name: 'Яка планета найближча до Сонця?' }).getByRole('button', { name: /^Flag:/ }).click();
  const dialog = page.getByRole('dialog');
  await expect(dialog.getByRole('button', { name: 'Надіслати повідомлення' })).toBeDisabled();
  await dialog.getByRole('textbox', { name: 'Опишіть проблему' }).fill('Приклад проблеми з текстом запитання.');
  await dialog.getByRole('button', { name: 'Надіслати повідомлення' }).click();
  await expect(dialog.getByRole('link', { name: 'Відкрити issue #42' })).toHaveAttribute('href', 'https://github.com/example/content/issues/42');
  expect(calls).toBe(1);
});
